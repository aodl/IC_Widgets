"""Pack pinned map units and local flag icons for the browser. See web/src/data/README.md."""
import base64
import io
import json
from pathlib import Path
import re
import sys
import tarfile

import cairosvg
from PIL import Image


def pack_geometry(source, target):
    data = bytearray()

    def unsigned(value):
        while value >= 128:
            data.append((value & 127) | 128)
            value >>= 7
        data.append(value)

    features = json.loads(source.read_text())["features"]
    units = []
    for feature in features:
        code = feature["properties"]["ISO_A2_EH"]
        geometry = feature["geometry"]
        polygons = geometry["coordinates"]
        if geometry["type"] == "Polygon":
            polygons = [polygons]
        rings = [ring for polygon in polygons for ring in polygon]
        units.append(code if re.fullmatch(r"[A-Z]{2}", code) else "")
        unsigned(len(rings))
        for ring in rings:
            unsigned(len(ring) - 1)
            x = y = 0
            for lon, lat in ring[:-1]:
                next_x, next_y = round(lon * 200), round(lat * 200)
                for delta in (next_x - x, next_y - y):
                    unsigned(delta * 2 if delta >= 0 else -delta * 2 - 1)
                x, y = next_x, next_y

    target.write_text("// Generated by scripts/build-country-assets.py. Source: Natural Earth.\n"
                      + f"export const units = {json.dumps(units, separators=(',', ':'))};\n"
                      + f"export const geometry = '{base64.b64encode(data).decode()}';\n")


def pack_flags(source, target):
    width, height, columns = 24, 18, 16
    with tarfile.open(source, "r:gz") as archive:
        files = sorted(member.name for member in archive.getmembers()
                       if re.search(r"/flags/4x3/[a-z]{2}\.svg$", member.name)
                       and Path(member.name).stem not in {"eu", "un", "xx"})
        atlas = Image.new("RGBA", (width * columns, height * ((len(files) + columns - 1) // columns)))
        codes = []
        for i, filename in enumerate(files):
            codes.append(Path(filename).stem.upper())
            svg = archive.extractfile(filename).read()
            png = cairosvg.svg2png(bytestring=svg, output_width=width, output_height=height)
            atlas.paste(Image.open(io.BytesIO(png)), (i % columns * width, i // columns * height))
        license_file = next(member for member in archive.getmembers() if re.fullmatch(r"[^/]+/LICENSE", member.name))
        license_text = archive.extractfile(license_file).read().decode().rstrip()
        target.with_name("FLAG-ICONS-LICENSE.txt").write_text(license_text + "\n")
    buffer = io.BytesIO()
    atlas.save(buffer, format="PNG", optimize=True)
    target.write_text("/*! flag-icons v7.2.3\n" + license_text + "\n*/\n"
                      + "// Generated by scripts/build-country-assets.py.\n"
                      + f"export const flagSize = [{width},{height},{columns}];\n"
                      + f"export const flagCodes = '{''.join(codes)}';\n"
                      + f"export const flagAtlas = '{base64.b64encode(buffer.getvalue()).decode()}';\n")


if __name__ == "__main__":
    destination = Path(__file__).resolve().parents[1] / "web/src/data"
    pack_geometry(Path(sys.argv[1]), destination / "map-units.js")
    pack_flags(Path(sys.argv[2]), destination / "flag-atlas.js")
